import { strict as assert } from 'node:assert';
import { pbkdf2Sync } from 'node:crypto';
import {verifyStoredPassword,PasswordVerificationUnavailableError} from './password-verification.ts';
const salt='0123456789abcdef0123456789abcdef', password='fixture-only-password-123';
const derive=async(p:string,s:string,n:number)=>pbkdf2Sync(p,Buffer.from(s,'hex'),n,32,'sha256').toString('hex');
const make=async(n:number)=>({password_salt:salt,password_iterations:n,password_hash:await derive(password,salt,n)});
const old=await make(310000), fresh=await make(100000);
const started=performance.now();assert.equal(await verifyStoredPassword(password,old,derive),true);
console.log('310k native Node verification ms:',Math.round(performance.now()-started),'NOT Workers timing');
assert.equal(await verifyStoredPassword('wrong',old,derive),false);
assert.equal(await verifyStoredPassword(password,fresh,derive),true);
const snapshot=JSON.stringify(old);let passed=0;
const limited=async(p:string,s:string,n:number)=>{passed=n;if(n>100000)throw new DOMException('cap','NotSupportedError');return derive(p,s,n)};
await assert.rejects(()=>verifyStoredPassword(password,old,limited),PasswordVerificationUnavailableError);
assert.equal(passed,310000);assert.equal(JSON.stringify(old),snapshot);
assert.equal(await verifyStoredPassword(password,fresh,limited),true);
let called=false;
await assert.rejects(()=>verifyStoredPassword(password,{...old,password_iterations:999999999},async()=>{called=true;return ''}),PasswordVerificationUnavailableError);
assert.equal(called,false);
await assert.rejects(()=>verifyStoredPassword(password,{...old,password_salt:'bad'},derive),PasswordVerificationUnavailableError);
